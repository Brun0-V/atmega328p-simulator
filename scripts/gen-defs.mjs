// Generates src/core/m328pdef.ts from an AVRA m328Pdef.inc file.
// Usage: node scripts/gen-defs.mjs /path/to/m328Pdef.inc
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync(process.argv[2] ?? 'm328Pdef.inc', 'utf8');
const equ = {};
const ioRegs = new Map(); // name -> data address (from the I/O register section)
const info = new Map(); // name -> { desc, group, bits }
let section = '';
let group = '';
let current = null;

for (const line of src.split(/\r?\n/)) {
  const sec = line.match(/^; \*{5} (.+?) \*+/);
  if (sec) {
    section = sec[1];
    if (!/DEFINITIONS|SPECIFY DEVICE|CPU REGISTER|DATA MEMORY|BOOTLOADER|INTERRUPT VECTORS/.test(section)) group = section;
    current = null;
    continue;
  }
  const head = line.match(/^; (\w+) - (.+)$/);
  if (head && group) {
    current = { desc: head[2].trim(), group, bits: Array(8).fill(null) };
    if (!info.has(head[1])) info.set(head[1], current);
    else current = info.get(head[1]);
    continue;
  }
  const m = line.match(/^\.equ\s+(\w+)\s*=\s*([^;]+)(?:;(.*))?/);
  if (!m) continue;
  const v = m[2].trim();
  const n = /^0x[0-9a-f]+$/i.test(v) ? parseInt(v, 16) : /^\d+$/.test(v) ? parseInt(v, 10) : equ[v.toUpperCase()];
  if (n === undefined) throw new Error(`Cannot resolve ${m[1]} = ${v}`);
  equ[m[1].toUpperCase()] = n;
  if (section.startsWith('I/O REGISTER DEFINITIONS')) {
    ioRegs.set(m[1], /MEMORY MAPPED/.test(m[3] ?? '') ? n : n + 0x20);
  } else if (current && n < 8) {
    current.bits[n] = m[1];
  }
}

const regs = [...ioRegs]
  .map(([name, addr]) => {
    const i = info.get(name);
    // Drop generic bit names like TCNT0_3 or OCR1AL5.
    const bits = (i?.bits ?? Array(8).fill(null)).map((b) => (b && /_\d$/.test(b) ? null : b));
    return { name, addr, desc: i?.desc ?? '', group: i?.group ?? '', bits };
  })
  .sort((a, b) => a.addr - b.addr);

const body = Object.entries(equ).map(([k, v]) => `  ${k}: ${v},`).join('\n');
writeFileSync(
  new URL('../src/core/m328pdef.ts', import.meta.url),
  `// Generated by scripts/gen-defs.mjs from AVRA's m328Pdef.inc. Do not edit.\n` +
    `// Low I/O registers use I/O addresses (0x00-0x3F); "memory mapped" ones use data addresses.\n` +
    `export const M328P_EQU: Record<string, number> = {\n${body}\n};\n\n` +
    `export interface IoRegister {\n  name: string;\n  /** Data-space address */\n  addr: number;\n  desc: string;\n  group: string;\n  /** Bit names, index = bit number */\n  bits: (string | null)[];\n}\n\n` +
    `export const M328P_REGS: IoRegister[] = ${JSON.stringify(regs, null, 1).replace(/\n\s*/g, ' ')
      .replace(/\}, \{/g, '},\n  {').replace(/^\[ /, '[\n  ').replace(/ \]$/, ',\n]')};\n`,
);
console.log(`wrote ${Object.keys(equ).length} symbols, ${regs.length} registers`);
